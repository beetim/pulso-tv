/** Draws one 24x24 path scaled to the size it is given. */
@Composable
private fun Glyph(path: String, color: Color, modifier: Modifier) {
    val parsed = remember(path) { PathParser().parsePathString(path).toPath() }
    Canvas(modifier) {
        val k = size.minDimension / 24f
        scale(k, k, pivot = Offset.Zero) { drawPath(parsed, color) }
    }
}

@Composable
fun GearIcon(color: Color, modifier: Modifier = Modifier.size(22.dp)) = Glyph(GEAR, color, modifier)

@Composable
fun FullscreenIcon(expand: Boolean, color: Color, modifier: Modifier = Modifier.size(22.dp)) =
    Glyph(if (expand) FULLSCREEN else FULLSCREEN_EXIT, color, modifier)

@Composable
fun PlayIcon(color: Color, modifier: Modifier = Modifier.size(24.dp)) = Glyph(PLAY, color, modifier)

@Composable
fun PauseIcon(color: Color, modifier: Modifier = Modifier.size(24.dp)) = Glyph(PAUSE, color, modifier)

@Composable
fun HeartIcon(filled: Boolean, color: Color, modifier: Modifier = Modifier.size(22.dp)) =
    Glyph(if (filled) HEART else HEART_OUTLINE, color, modifier)

/** Speech bubble; the crossed-out bubble when the chat is hidden. */
@Composable
fun ChatIcon(visible: Boolean, color: Color, modifier: Modifier = Modifier.size(22.dp)) =
    Glyph(if (visible) CHAT else CHAT_OFF, color, modifier)

/** Person: head and shoulders. */
@Composable
fun ChannelIcon(color: Color, modifier: Modifier = Modifier.size(22.dp)) = Glyph(PERSON, color, modifier)

/** Three vertical dots. */
@Composable
fun MoreIcon(color: Color, modifier: Modifier = Modifier.size(22.dp)) = Glyph(MORE, color, modifier)

/** Speaker with sound waves, or crossed out when [muted]. */
@Composable
fun VolumeIcon(muted: Boolean, color: Color, modifier: Modifier = Modifier.size(22.dp)) =
    Glyph(if (muted) VOLUME_OFF else VOLUME_UP, color, modifier)

@Composable
